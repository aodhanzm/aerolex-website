// AeroLex edit mode: a small local web server that shows the website with an editing toolbar on top.
//
// Start it with "Start edit mode.bat" (or: node _tools/edit-mode/server.mjs) from the website folder,
// then open http://127.0.0.1:8780/. It only listens on this computer, never on the internet.
//
// What it can save:
//   - Text: changes the words inside the page's HTML file.
//   - Look and placement (font, size, weight, spacing, nudging position): written as rules into
//     assets/edit-overrides.css, linked from the page. The element gets a small data-edit="..." tag
//     so the rule can find it.
// Every save is an ordinary file change, so it shows up in git for Claude/Codex to review before publishing.
// Pages built by other projects (brazalete/, chinese/, sanctum/) are read-only here, because their
// next rebuild would wipe any edit made directly to the website copy.
import http from 'node:http';
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));          // This tool's own folder.
const site = path.resolve(here, '..', '..');                         // The website folder (two levels up).
const PORT = 8780;                                                   // Local address: http://127.0.0.1:8780/
const OVERRIDES = path.join(site, 'assets', 'edit-overrides.css');   // Where look/placement rules are saved.
const OVERRIDES_LINK = '<link rel="stylesheet" href="/assets/edit-overrides.css"> <!-- Look and placement changes saved from the local edit mode. -->';
const READ_ONLY = /^(brazalete|chinese|sanctum|astro)\//;            // Generated by other projects: never edit here.
const undo = [];                                                     // Previous file contents, newest last, for "Undo last save".

// Tags whose words count as editable text.
const TEXT_TAGS = new Set(['h1', 'h2', 'h3', 'h4', 'h5', 'h6', 'p', 'a', 'span', 'li', 'button', 'dt', 'dd', 'label', 'summary', 'strong', 'em', 'b', 'i', 'small', 'output', 'figcaption', 'blockquote']);
// Tags that never have a closing tag, so they never hold text.
const VOID = new Set(['area', 'base', 'br', 'col', 'embed', 'hr', 'img', 'input', 'link', 'meta', 'source', 'track', 'wbr']);

// Fingerprint of a file's contents, so a save made from an out-of-date page is refused instead of corrupting the file.
const hash = text => crypto.createHash('sha1').update(text).digest('hex').slice(0, 12);

// Walk through an HTML file and list every element that holds plain text, with its exact position in the file.
// Each entry: where its opening tag starts (tagStart), where it ends (openEnd), and where its text begins/ends.
function findTextElements(src) {
  const found = [];
  const stack = [];
  const re = /<!--[\s\S]*?-->|<(script|style)\b[^>]*>[\s\S]*?<\/\1\s*>|<\/?([a-zA-Z][a-zA-Z0-9-]*)\b[^>]*?>/g;
  let m;
  while ((m = re.exec(src))) {
    if (m[0].startsWith('<!--') || m[1]) continue;              // Skip comments and the insides of scripts/styles.
    const tag = m[2].toLowerCase();
    if (m[0][1] === '/') {                                       // A closing tag: find its matching opening tag.
      for (let i = stack.length - 1; i >= 0; i--) {
        if (stack[i].tag !== tag) continue;
        const open = stack[i];
        stack.length = i;                                        // Anything left open inside it is closed too.
        const inner = src.slice(open.openEnd, m.index);
        if (TEXT_TAGS.has(tag) && inner.trim()) {
          // "plain" = only words and line breaks inside, so its words can be safely rewritten.
          // Others (e.g. a heading with a coloured dot inside) can still have their look and position saved.
          const plain = !/<(?!br\s*\/?>)/i.test(inner);
          found.push({ tagStart: open.tagStart, openEnd: open.openEnd, textStart: plain ? open.openEnd : '', textEnd: plain ? m.index : '' });
        }
        break;
      }
    } else if (!VOID.has(tag) && !m[0].endsWith('/>')) {
      stack.push({ tag, tagStart: m.index, openEnd: m.index + m[0].length });
    }
  }
  return found;
}

// Before sending a page to the browser, label each editable element with its position in the file
// (data-edit-src="tagStart:textStart:textEnd") and add the editing toolbar. These labels exist only
// in what the browser sees here; the file on disk is not changed by viewing it.
function annotate(src, rel) {
  const items = findTextElements(src).sort((a, b) => b.tagStart - a.tagStart);   // Work back to front so positions stay valid.
  let out = src;
  for (const it of items) {
    const at = it.openEnd - 1 - (src[it.openEnd - 2] === '/' ? 1 : 0);           // Just before the ">" of the opening tag.
    out = out.slice(0, at) + ` data-edit-src="${it.tagStart}:${it.textStart}:${it.textEnd}"` + out.slice(at);
  }
  // Tell the toolbar which file this is, its fingerprint, and whether it may be edited.
  const info = `<script>window.__EDIT = ${JSON.stringify({ file: rel, version: hash(src), readOnly: READ_ONLY.test(rel) })};</script>`;
  const tools = '<link rel="stylesheet" href="/__edit/editor.css"><script defer src="/__edit/editor.js"></script>';
  return out.includes('</body>') ? out.replace('</body>', info + tools + '</body>') : out + info + tools;
}

// Turn typed text into safe HTML: escape the three characters HTML treats specially, keep line breaks as <br>.
const toHtml = text => text.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/\r?\n/g, '<br>');

// Make sure an HTML page links the overrides stylesheet (added once, right before </head>).
function ensureOverridesLink(src) {
  return src.includes('/assets/edit-overrides.css') ? src : src.replace('</head>', OVERRIDES_LINK + '\n</head>');
}

// Write the CSS rule for one element into the overrides file. Only the settings changed this time are sent;
// they are added on top of anything saved before for the same element. reset = remove the element's rule entirely.
function saveRule(id, styles, reset) {
  const css = fs.existsSync(OVERRIDES) ? fs.readFileSync(OVERRIDES, 'utf8')
    : '/* Look and placement changes saved from the local edit mode (_tools/edit-mode). One rule per edited element. */\n';
  // Only these properties can be saved, and only with plain values (no semicolons or braces sneaking in).
  const allowed = ['font-family', 'font-size', 'font-weight', 'font-style', 'letter-spacing', 'line-height', 'text-align', 'translate'];
  const pattern = new RegExp(`\\[data-edit="${id}"\\] \\{([^}]*)\\}\\n`);
  // Start from the element's earlier saved settings (if any), unless this is a reset.
  const merged = {};
  const earlier = css.match(pattern);
  if (earlier && !reset) for (const part of earlier[1].split(';')) { const [k, ...v] = part.split(':'); if (k.trim()) merged[k.trim()] = v.join(':').trim(); }
  for (const p of allowed) if (p in styles && /^[\w\s.,'"%#()-]*$/.test(styles[p])) merged[p] = styles[p];
  // Empty values mean "back to the page's normal look" for that setting, so they're dropped.
  const body = Object.entries(merged).filter(([, v]) => v).map(([k, v]) => `${k}: ${v};`).join(' ');
  const rule = body ? `[data-edit="${id}"] { ${body} }\n` : '';
  const next = pattern.test(css) ? css.replace(pattern, rule) : css + rule;
  remember(OVERRIDES, css);
  fs.writeFileSync(OVERRIDES, next);
}

// Keep the previous contents so "Undo last save" can put them back (a null means the file didn't exist yet).
function remember(file, previous) { undo.push({ file, previous: fs.existsSync(file) ? previous : null }); }

// Read a JSON request body (small, from the toolbar only).
function readBody(req) {
  return new Promise((resolve, reject) => {
    let data = '';
    req.on('data', c => { data += c; if (data.length > 1e6) reject(new Error('Too large')); });
    req.on('end', () => { try { resolve(JSON.parse(data)); } catch (e) { reject(e); } });
  });
}

// Resolve a requested address to a file inside the website folder; refuse anything that escapes it.
function fileFor(urlPath) {
  let rel = decodeURIComponent(urlPath.split('?')[0]).replace(/^\/+/, '');
  if (rel === '' || rel.endsWith('/')) rel += 'index.html';
  const full = path.resolve(site, rel);
  if (!full.startsWith(site + path.sep)) return null;
  if (fs.existsSync(full) && fs.statSync(full).isDirectory()) return { full: path.join(full, 'index.html'), rel: rel + '/index.html' };
  return { full, rel: rel.replace(/\\/g, '/') };
}

// File types the browser needs labelled correctly.
const TYPES = { '.html': 'text/html; charset=utf-8', '.css': 'text/css', '.js': 'text/javascript', '.json': 'application/json', '.svg': 'image/svg+xml', '.png': 'image/png', '.jpg': 'image/jpeg', '.jpeg': 'image/jpeg', '.webp': 'image/webp', '.ico': 'image/x-icon', '.xml': 'application/xml', '.txt': 'text/plain', '.woff2': 'font/woff2' };

const send = (res, code, body, type = 'application/json') => { res.writeHead(code, { 'Content-Type': type, 'Cache-Control': 'no-store' }); res.end(body); };

http.createServer(async (req, res) => {
  try {
    const url = new URL(req.url, 'http://local');
    // The toolbar's own files.
    if (url.pathname === '/__edit/editor.js' || url.pathname === '/__edit/editor.css') {
      const f = path.join(here, path.basename(url.pathname));
      return send(res, 200, fs.readFileSync(f), TYPES[path.extname(f)]);
    }
    // Save new words for one element.
    if (req.method === 'POST' && url.pathname === '/__edit/text') {
      const b = await readBody(req);
      const target = fileFor('/' + b.file);
      if (!target || READ_ONLY.test(target.rel)) return send(res, 403, '{"error":"This page is read-only here."}');
      const src = fs.readFileSync(target.full, 'utf8');
      if (hash(src) !== b.version) return send(res, 409, '{"error":"The file changed since this page loaded. Reload and try again."}');
      remember(target.full, src);
      fs.writeFileSync(target.full, src.slice(0, b.textStart) + toHtml(b.text) + src.slice(b.textEnd));
      return send(res, 200, '{"ok":true}');
    }
    // Save look/placement for one element: tag it with data-edit="..." (if new) and write its CSS rule.
    if (req.method === 'POST' && url.pathname === '/__edit/style') {
      const b = await readBody(req);
      const target = fileFor('/' + b.file);
      if (!target || READ_ONLY.test(target.rel)) return send(res, 403, '{"error":"This page is read-only here."}');
      let src = fs.readFileSync(target.full, 'utf8');
      if (hash(src) !== b.version) return send(res, 409, '{"error":"The file changed since this page loaded. Reload and try again."}');
      remember(target.full, src);
      const openEnd = src.indexOf('>', b.tagStart);
      const openTag = src.slice(b.tagStart, openEnd);
      let id = (openTag.match(/data-edit="([\w-]+)"/) || [])[1];
      if (!id) {
        id = 'e-' + crypto.randomBytes(3).toString('hex');                     // Short random label, e.g. e-3fa9c1.
        const at = openEnd - (src[openEnd - 1] === '/' ? 1 : 0);
        src = src.slice(0, at) + ` data-edit="${id}"` + src.slice(at);
      }
      fs.writeFileSync(target.full, ensureOverridesLink(src));
      saveRule(id, b.styles || {}, b.reset === true);
      return send(res, 200, JSON.stringify({ ok: true, id }));
    }
    // Put back the most recent save.
    if (req.method === 'POST' && url.pathname === '/__edit/undo') {
      const last = undo.pop();
      if (!last) return send(res, 200, '{"ok":false,"message":"Nothing to undo in this session."}');
      if (last.previous === null) fs.rmSync(last.file, { force: true }); else fs.writeFileSync(last.file, last.previous);
      // A style save changed two files (page + overrides); undo both together.
      if (undo.length && last.file === OVERRIDES) { const page = undo.pop(); fs.writeFileSync(page.file, page.previous); }
      return send(res, 200, '{"ok":true}');
    }
    // Ordinary files: HTML pages get the labels and toolbar; everything else is sent as-is.
    const target = fileFor(url.pathname);
    if (!target || !fs.existsSync(target.full)) return send(res, 404, 'Not found', 'text/plain');
    const ext = path.extname(target.full).toLowerCase();
    if (ext === '.html') return send(res, 200, annotate(fs.readFileSync(target.full, 'utf8'), target.rel), TYPES['.html']);
    return send(res, 200, fs.readFileSync(target.full), TYPES[ext] || 'application/octet-stream');
  } catch (e) {
    send(res, 500, JSON.stringify({ error: String(e.message || e) }));
  }
}).listen(PORT, '127.0.0.1', () => {
  console.log(`Edit mode running: http://127.0.0.1:${PORT}/  (close this window to stop)`);
});
